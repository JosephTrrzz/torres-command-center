// Run with Node after changing studio-torres-runtime.ts. The checked-in literal
// is data to the Worker bundler, so keepNames/minification cannot alter it.
import { readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { transform } from 'esbuild';
import { parse } from 'acorn';

export const generatedPath = new URL('./studio-torres-runtime.generated.ts', import.meta.url);
export async function generateRuntimeModule() {
  const source = await readFile(new URL('./studio-torres-runtime.ts', import.meta.url), 'utf8');
  const { code } = await transform(source.replace('export function runTorresPatches(', 'function runTorresPatches('), {
    loader: 'ts', target: 'es2022', keepNames: false, minify: false, legalComments: 'none',
  });
  // Refuse emitted imports, exports, or helpers outside the serialized function.
  const ast = parse(code, { ecmaVersion: 2022 });
  if (ast.body.length !== 1 || ast.body[0].type !== 'FunctionDeclaration' || ast.body[0].id.name !== 'runTorresPatches') {
    throw Error('Runtime must be one self-contained function without external helpers.');
  }
  return '// Generated by studio-torres-runtime.generate.mjs; do not edit.\n'
    + 'export const TORRES_RUNTIME_SOURCE = ' + JSON.stringify(code.trim()) + ';\n';
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const generated = await generateRuntimeModule();
  if (process.argv.includes('--check')) {
    if (await readFile(generatedPath, 'utf8') !== generated) throw Error('Generated runtime is stale. Regenerate it.');
  } else await writeFile(generatedPath, generated);
}
